// What the "I'm on call" widget shows (iOS, modules/brigade-widget): a snapshot of the member's on-call stretches,
// worked out here from the shard's schedules and overrides and kept in the App Group, where the widget reads it.
// The widget never talks to the network or holds credentials: it only walks the stretches with the clock, so it
// flips at each handoff without the app running, and says "Open Brigade to update" once the snapshot is older than
// `WIDGET_STALE_MS` (an override added since would not be in it). Pure, so it is tested in Node.
import type { Locale } from "@freecorps/brigade-i18n";
import { nextHandoffs, type OverrideRow, type ScheduleRow } from "@freecorps/brigade-schema";
import { UPCOMING_MS } from "@/lib/oncall";

/** How long the widget trusts a snapshot: past this it asks to open the app instead of guessing. */
export const WIDGET_STALE_MS = 24 * 60 * 60 * 1000;
/** Stretches kept: far more than a day's handoffs need, and the snapshot stays small. */
export const WIDGET_MAX_SHIFTS = 64;
/** Handoffs worked out per schedule. */
const SEGMENTS = 120;

/**
 * The App Group snapshot, version 1. Times are ms since the epoch. `shifts`: the member's stretches on call, merged
 * across schedules (on two at once is on call until the last ends), soonest first, `[start, end]` with `end` null when
 * no handoff ends it within the look-ahead. `locale`: the app's language, so the widget's bundled strings and times
 * match the app's, not only the system's. Strings are not in it: the widget bundles them (`widget_*` in
 * packages/i18n, generated by plugins/widget.ts).
 */
export type WidgetSnapshot = {
  v: 1;
  writtenAt: number;
  staleAt: number;
  locale: Locale;
  /** Whether the workspace has any schedule: without one, "No on-call schedules" rather than "Not on call". */
  schedules: boolean;
  shifts: [number, number | null][];
  /** Open (not resolved) incidents when the snapshot was written; null when not known. */
  openIncidents: number | null;
};

export function widgetSnapshot(input: {
  schedules: readonly ScheduleRow[];
  overrides: readonly OverrideRow[];
  userId: string;
  now: number;
  locale: Locale;
  openIncidents: number | null;
}): WidgetSnapshot {
  const { schedules, overrides, userId, now } = input;
  const horizon = now + UPCOMING_MS;
  const stretches: [number, number | null][] = [];
  for (const schedule of schedules) {
    const segments = nextHandoffs(schedule, overrides, now, horizon, SEGMENTS + 1);
    const capped = segments.length > SEGMENTS;
    if (capped) segments.pop();
    segments.forEach((segment, index) => {
      if (segment.userId !== userId) return;
      // The last segment ends where the look-ahead stopped, not at a handoff (as in onCallView).
      const last = !capped && index === segments.length - 1;
      stretches.push([segment.start, last ? null : segment.end]);
    });
  }
  return {
    v: 1,
    writtenAt: now,
    staleAt: now + WIDGET_STALE_MS,
    locale: input.locale,
    schedules: schedules.length > 0,
    shifts: merge(stretches).slice(0, WIDGET_MAX_SHIFTS),
    openIncidents: input.openIncidents,
  };
}

/** Overlapping or touching stretches as one, soonest first. An open end swallows everything after it. */
function merge(stretches: [number, number | null][]): [number, number | null][] {
  const sorted = [...stretches].sort((a, b) => a[0] - b[0]);
  const out: [number, number | null][] = [];
  for (const [start, end] of sorted) {
    const previous = out.at(-1);
    if (previous && (previous[1] === null || start <= previous[1])) {
      previous[1] = previous[1] === null || end === null ? null : Math.max(previous[1], end);
    } else {
      out.push([start, end]);
    }
  }
  return out;
}

/**
 * What the widget shows at `at`, as its Swift copy decides it (modules/brigade-widget/widget/WidgetState.swift).
 * Kept here so the decision is tested in CI; the two must agree.
 */
export type WidgetState =
  | { kind: "signed-out" }
  | { kind: "stale" }
  | { kind: "no-schedules" }
  | { kind: "on"; until: number | null }
  | { kind: "off"; next: number | null };

export function widgetState(snapshot: WidgetSnapshot | null, at: number): WidgetState {
  if (!snapshot) return { kind: "signed-out" };
  if (at >= snapshot.staleAt) return { kind: "stale" };
  if (!snapshot.schedules) return { kind: "no-schedules" };
  for (const [start, end] of snapshot.shifts) {
    if (start <= at && (end === null || at < end)) return { kind: "on", until: end };
    if (start > at) return { kind: "off", next: start };
  }
  return { kind: "off", next: null };
}

/**
 * The instants the widget's timeline needs an entry at, from `from` on: `from` itself, every handoff before the
 * snapshot goes stale, and the moment it does.
 */
export function widgetTimeline(snapshot: WidgetSnapshot, from: number): number[] {
  const times = new Set<number>([from]);
  for (const [start, end] of snapshot.shifts) {
    for (const at of [start, end]) {
      if (at !== null && at > from && at < snapshot.staleAt) times.add(at);
    }
  }
  if (snapshot.staleAt > from) times.add(snapshot.staleAt);
  return [...times].sort((a, b) => a - b);
}
