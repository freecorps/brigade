// Writes `src/case-fold.ts`: the characters JavaScript's `iu` flags treat as the same letter (they share a simple case
// folding), which `pattern.ts` uses to ignore case as `RegExp` does. Derived from the running engine's own `RegExp`,
// so the table follows its Unicode version; rerun after a Node upgrade and commit the result:
//
//   vpx packages/schema/scripts/case-fold.ts
//
// `tests/pattern.test.ts` derives it again and compares, on an engine of the same Unicode version.

import { writeFileSync } from "node:fs";

/** Every code point that has a case or changes under case mapping or folding: the only ones that can share a fold. */
function cased(): number[] {
  const property = /[\p{Cased}\p{Changes_When_Casefolded}\p{Changes_When_Casemapped}]/u;
  const out: number[] = [];
  for (let code = 0; code <= 0x10ffff; code++) {
    if (code >= 0xd800 && code <= 0xdfff) continue;
    if (property.test(String.fromCodePoint(code))) out.push(code);
  }
  return out;
}

/** The sets of two or more code points that `RegExp` with `iu` takes for each other, each sorted, by first member. */
export function caseFoldGroups(): number[][] {
  const codes = cased();
  const chars = codes.map((code) => String.fromCodePoint(code));
  const grouped = new Set<number>();
  const groups: number[][] = [];
  codes.forEach((code, index) => {
    if (grouped.has(code)) return;
    const char = chars[index]!.replace(/[\\\]\[^-]/g, "\\$&");
    const same = new RegExp(`^[${char}]$`, "iu");
    const group = codes.filter((_, at) => same.test(chars[at]!));
    for (const member of group) grouped.add(member);
    if (group.length > 1) groups.push(group);
  });
  return groups;
}

/**
 * The groups as runs: `start count stride offset…` in base 36, runs joined by commas. A run is `count` groups, the
 * first at `start` and each next one `stride` further, whose other members sit at the same `offset`s from the first.
 */
export function encode(groups: number[][]): string[] {
  type Run = { start: number; count: number; stride: number; offsets: string };
  const runs: Run[] = [];
  for (const group of groups) {
    const offsets = group
      .slice(1)
      .map((code) => code - group[0]!)
      .join(" ");
    const last = runs.at(-1);
    if (last && last.offsets === offsets) {
      const stride = group[0]! - (last.start + (last.count - 1) * last.stride);
      if (last.count === 1 || stride === last.stride) {
        last.stride = stride;
        last.count++;
        continue;
      }
    }
    runs.push({ start: group[0]!, count: 1, stride: 1, offsets });
  }
  const encoded = runs.map((run) =>
    [run.start, run.count, run.stride, ...run.offsets.split(" ").map(Number)]
      .map((value) => value.toString(36))
      .join(" "),
  );
  // Lines of about a hundred characters, split between runs.
  const lines: string[] = [];
  for (const run of encoded) {
    const last = lines.at(-1);
    if (last !== undefined && last.length + run.length < 100) lines[lines.length - 1] = `${last},${run}`;
    else lines.push(run);
  }
  return lines;
}

if (import.meta.filename === process.argv[1]) {
  const lines = encode(caseFoldGroups());
  const source = `// Generated by \`vpx packages/schema/scripts/case-fold.ts\` from RegExp \`iu\` (Unicode ${process.versions.unicode}); do not edit.
// The characters that share a simple case folding, as runs (\`start count stride offset…\`, base 36): see the script.

/** The Unicode version of the engine the table was derived from. */
export const CASE_FOLD_UNICODE = "${process.versions.unicode}";

export const CASE_FOLD_RUNS = [
${lines.map((line) => `  "${line}",`).join("\n")}
].join(",");
`;
  writeFileSync(new URL("../src/case-fold.ts", import.meta.url), source);
}
