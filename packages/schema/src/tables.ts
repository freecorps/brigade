/** Why a level's target could not be paged when it fired (RFC 0006 "Who is paged"). */
export type EscalationMiss = {
  /** The member it resolved to; null for a schedule with nobody on call, or deleted. */
  userId: string | null;
  reason: Extract<
    PageFailure,
    "no_devices" | "nobody_on_call" | "schedule_missing" | "not_a_member"
  >;
  scheduleId: string | null;
  /** The schedule's name when the level fired; null for a member, or a deleted schedule. */
  schedule: string | null;
};

/**
 * Why a level was paged: the run `started`, the level before timed out, the ones before were `unreachable`, or
 * every push of the level before failed (`undelivered`: no device took it, `escalation.unreached`); for the interim
 * rule (`level` null) also `exhausted` (every level and repeat paged, nobody acknowledged) or `stalled` (a level kept
 * failing to fire, `escalation.fallback`).
 */
export type EscalationReason =
  | "started"
  | "timeout"
  | "unreachable"
  | "undelivered"
  | "exhausted"
  | "stalled";

/** One level an escalation run paged. */
export type EscalationPage = {
  /** 1-based; null: everyone who can respond was paged (the interim rule), for `reason`. */
  level: number | null;
  /** 0 the first time through the levels, then 1 to the policy's `repeat`. */
  round: number;
  at: number;
  /** Who the level resolved to and could reach (schedules to whoever was on call then). */
  userIds: string[];
  /**
   * Targets of this level, and of the unreachable levels skipped to get here, that could not be paged: the first
   * `MAX_PAGE_MISSES` of them (the incident row stays small); `missedCount` says how many there were.
   */
  missed: EscalationMiss[];
  missedCount: number;
  reason: EscalationReason;
  /** The run's page before this one paged again: its event was lost (RFC 0006 "A lost page"). */
  again?: boolean;
  /** For `undelivered`: the level (1-based) none of whose pushes any device took. */
  unreached?: number;
};

export type EscalationStatus = "running" | "acknowledged" | "resolved" | "exhausted";

/**
 * An escalation run (RFC 0003 "Escalation run"): the policy as it was when the run started, where it is, and every
 * level it paged. Written by `escalation.start` and `escalation.advance`; `incident.ack` and resolving stop it.
 */
export type Escalation = {
  policyId: string;
  policyName: string;
  /**
   * The monitor whose own policy this is (its name when the run started), for an incident that monitor opened;
   * null or absent: the workspace's default policy.
   */
  monitor?: { id: string; name: string } | null;
  /** Likewise the alert route whose policy this is, for an incident an alert source opened through it. */
  route?: { id: string; name: string } | null;
  levels: EscalationLevel[];
  repeat: number;
  /** The event whose page started the run: a redelivery of it pages the same level again, never a new run. */
  eventId: string;
  /** Who caused that event: not pushed (they know), and left out of the interim rule's fallback. */
  causedBy: string;
  status: EscalationStatus;
  startedAt: number;
  /** When it stopped (acknowledged, resolved, exhausted); null while running. */
  endedAt: number | null;
  /** When the next level fires; null once it stopped. */
  nextAt: number | null;
  /** How many pages the run made: the step `escalation.advance` names, which `pages` (capped) cannot. */
  paged: number;
  /** The last `MAX_ESCALATION_PAGES` pages, oldest first. */
  pages: EscalationPage[];
};

/** Who a level pages: a schedule (whoever is on call when it fires) or a member. */
export type EscalationTarget = { kind: EscalationTargetKind; id: string };

export type EscalationLevel = {
  id: string; // lvl_<ULID>, made by the client
  targets: EscalationTarget[];
  /** Minutes before the next level fires when nobody acknowledges. */
  timeoutMinutes: number;
};

/** An escalation policy (RFC 0003 "Escalation policies"). */
export type EscalationPolicyRow = {
  id: string; // esc_<ULID>, made by the client
  name: string;
  levels: EscalationLevel[];
  /** How many more times the levels run when nobody acknowledges. */
  repeat: number;
  /** Pages use the default policy; at most one is. */
  isDefault: boolean;
  createdAt: number;
  createdBy: string;
  updatedAt: number;
};

/**
 * Server-only: when a running escalation's next level fires, so the shard's alarm reads only running ones.
 * `failingSince`: when the alarm first found the level due and could not fire it (absent while it fires), so the
 * stall fallback is measured from the first refusal, however late the alarm came.
 */
export type EscalationTimerRow = { id: string; at: number; failingSince?: number | null };

/** What a timeline entry records, by `kind` (RFC 0003 "TimelineEntry"). */
export type TimelineEntry =
  | { kind: "declared"; title: string; severity: Severity }
  | { kind: "status_changed"; from: IncidentStatus; to: IncidentStatus }
  | { kind: "severity_changed"; from: Severity; to: Severity }
  | { kind: "acknowledged" }
  /** `from` and `to` are member ids; null: nobody (assigned from nobody, or unassigned). */
  | { kind: "role_assigned"; role: IncidentRole; from: string | null; to: string | null }
  /** A written update (`incident.postUpdate`). */
  | { kind: "update"; body: string }
  /** The alert of the monitor that opened the incident resolved; the monitor's name as it was then. */
  | {
      kind: "alert_resolved";
      monitorId: string;
      monitor: string;
      reason: "recovered" | "paused" | "deleted";
    }
  /**
   * Every alert-source alert on the incident resolved, but people had already worked on it (acknowledged, took a
   * role, wrote an update or moved it on), so it stays open for them to close (`alert.ingest`).
   */
  | { kind: "alerts_resolved" }
  /**
   * A page reached nobody, or not `userId` on any of their devices (`notification.fail`, RFC 0005); `schedule` names
   * an escalation level's schedule that had nobody on call (absent on other entries).
   */
  | {
      kind: "page_failed";
      userId: string | null;
      reason: PageFailure;
      schedule?: string | null;
      /**
       * The escalation page it belongs to: the run (its `eventId`) and the page's step (1-based count of the run's
       * pages), so a page's failures are told apart from the next one's. Absent outside a run.
       */
      run?: string;
      step?: number;
    }
  /**
   * An escalation level was paged (RFC 0006 "Who is paged"): `level` 1-based, or null for everyone who can respond;
   * `reason` says why this level (`EscalationReason`).
   */
  | {
      kind: "escalated";
      level: number | null;
      round: number;
      userIds: string[];
      reason: EscalationReason;
      /** Everyone who can respond after earlier levels paged someone: no later level could reach anyone. */
      later?: boolean;
      /** The run's first page: who caused it, reached without a push (they know). */
      causedBy?: string;
      /** The page before paged again, the same level and people: its event was lost. */
      again?: boolean;
      /** For `undelivered`: the level none of whose pushes any device took, so this one was paged at once. */
      unreached?: number;
    }
  /** Every level and repeat was paged and nobody acknowledged, so everyone who can respond was paged. */
  | {
      kind: "escalation_exhausted";
      levels: number;
      rounds: number;
    }
  /**
   * The email notifier could not email `userId` (`notification.failEmail`, RFC 0005 "Email"): `about` says which
   * email, the one telling a member their page did not reach them or the one telling an owner nobody was paged.
   */
  | { kind: "email_failed"; userId: string; reason: EmailFailure; about: EmailAbout }
  /** The Slack notifier gave up on the incident's channel message (`notification.failSlack`, RFC 0011). */
  | { kind: "slack_failed"; reason: SlackFailure }
  /** An update published to the status page (`incident.publishUpdate`, RFC 0012): what the public was told. */
  | { kind: "status_published"; status: PublicStatus; body: string }
  /**
   * What the status page says was corrected (RFC 0012 "Corrections"): an update's text `edited` (`body`: the new
   * text), an update `removed` (`body`: the text taken down) or the incident `withdrawn` (`body`: its public title).
   */
  | { kind: "status_corrected"; change: StatusCorrection; body: string }
  /**
   * The incident's type changed (`incident.setType`): the types' names then; null: none. `fromDeleted`: the type it
   * had was deleted, so `from` is null (entries written before it read a null `from` with a null `to` that way).
   */
  | { kind: "type_changed"; from: string | null; to: string | null; fromDeleted?: boolean }
  /** Services named or taken off (`incident.setServices`), by their names then. */
  | { kind: "services_changed"; added: string[]; removed: string[] }
  /**
   * A custom field was set or cleared (`incident.setField`), by the field's name then. `value` is the text, link or
   * number; a select's options are `labels` as they read then (and `value` null). Both null: cleared.
   */
  | {
      kind: "field_changed";
      field: string;
      fieldKind: FieldKind;
      value: string | number | string[] | null;
      labels?: string[];
    }
  /** A follow-up was added, edited, completed, reopened or removed (RFC 0013), by its title then. */
  | {
      kind: "follow_up";
      change: "added" | "edited" | "done" | "reopened" | "removed";
      title: string;
    }
  /** The postmortem was first saved (`started`), or Workers AI wrote a draft of it (`ai_drafted`). */
  | { kind: "postmortem"; change: "started" | "ai_drafted" };

