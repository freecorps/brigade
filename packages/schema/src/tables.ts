// Timestamps are epoch milliseconds (RFC 0004 "Shared core"); ISO strings appear only at the edges
// (event envelopes, UI formatting).

/** WorkspaceDO's incident index (RFC 0002). */
export type IncidentRow = {
  id: string; // inc_<ULID>, generated by the client that declared it
  number: number | null; // INC-<number>, allocated by the server; null in a client's optimistic row
  title: string;
  severity: Severity;
  status: IncidentStatus;
  declaredAt: number;
  declaredBy: string;
  /** The first acknowledgement, which stops paging (RFC 0003); null until someone acknowledges. */
  acknowledgedAt: number | null;
  acknowledgedBy: string | null;
  /** Who holds each incident role (member ids); a role nobody holds is absent. Absent on rows from before roles. */
  roles?: { [R in IncidentRole]?: string };
  /** How many timeline entries the incident has: the last entry's `seq`. Absent on rows from before timelines. */
  timelineSeq?: number;
  /** The last escalation run of the incident's pages (RFC 0003 "Escalation run"); absent when none ran. */
  escalation?: Escalation | null;
  updatedAt: number;
};

/** Why a level's target could not be paged when it fired (RFC 0006 "Who is paged"). */
export type EscalationMiss = {
  /** The member it resolved to; null for a schedule with nobody on call, or deleted. */
  userId: string | null;
  reason: Extract<
    PageFailure,
    "no_devices" | "nobody_on_call" | "schedule_missing" | "not_a_member"
  >;
  scheduleId: string | null;
  /** The schedule's name when the level fired; null for a member, or a deleted schedule. */
  schedule: string | null;
};

/**
 * Why a level was paged: the run `started`, the level before timed out, the ones before were `unreachable`; for the
 * interim rule (`level` null) also `exhausted` (every level and repeat paged, nobody acknowledged) or `stalled` (a
 * level kept failing to fire, `escalation.fallback`).
 */
export type EscalationReason = "started" | "timeout" | "unreachable" | "exhausted" | "stalled";

/** One level an escalation run paged. */
export type EscalationPage = {
  /** 1-based; null: everyone who can respond was paged (the interim rule), for `reason`. */
  level: number | null;
  /** 0 the first time through the levels, then 1 to the policy's `repeat`. */
  round: number;
  at: number;
  /** Who the level resolved to and could reach (schedules to whoever was on call then). */
  userIds: string[];
  /**
   * Targets of this level, and of the unreachable levels skipped to get here, that could not be paged: the first
   * `MAX_PAGE_MISSES` of them (the incident row stays small); `missedCount` says how many there were.
   */
  missed: EscalationMiss[];
  missedCount: number;
  reason: EscalationReason;
  /** The run's page before this one paged again: its event was lost (RFC 0006 "A lost page"). */
  again?: boolean;
};

export type EscalationStatus = "running" | "acknowledged" | "resolved" | "exhausted";

/**
 * An escalation run (RFC 0003 "Escalation run"): the policy as it was when the run started, where it is, and every
 * level it paged. Written by `escalation.start` and `escalation.advance`; `incident.ack` and resolving stop it.
 */
export type Escalation = {
  policyId: string;
  policyName: string;
  levels: EscalationLevel[];
  repeat: number;
  /** The event whose page started the run: a redelivery of it pages the same level again, never a new run. */
  eventId: string;
  /** Who caused that event: not pushed (they know), and left out of the interim rule's fallback. */
  causedBy: string;
  status: EscalationStatus;
  startedAt: number;
  /** When it stopped (acknowledged, resolved, exhausted); null while running. */
  endedAt: number | null;
  /** When the next level fires; null once it stopped. */
  nextAt: number | null;
  /** How many pages the run made: the step `escalation.advance` names, which `pages` (capped) cannot. */
  paged: number;
  /** The last `MAX_ESCALATION_PAGES` pages, oldest first. */
  pages: EscalationPage[];
};

/** Who a level pages: a schedule (whoever is on call when it fires) or a member. */
export type EscalationTarget = { kind: EscalationTargetKind; id: string };

export type EscalationLevel = {
  id: string; // lvl_<ULID>, made by the client
  targets: EscalationTarget[];
  /** Minutes before the next level fires when nobody acknowledges. */
  timeoutMinutes: number;
};

/** An escalation policy (RFC 0003 "Escalation policies"). */
export type EscalationPolicyRow = {
  id: string; // esc_<ULID>, made by the client
  name: string;
  levels: EscalationLevel[];
  /** How many more times the levels run when nobody acknowledges. */
  repeat: number;
  /** Pages use the default policy; at most one is. */
  isDefault: boolean;
  createdAt: number;
  createdBy: string;
  updatedAt: number;
};

/**
 * Server-only: when a running escalation's next level fires, so the shard's alarm reads only running ones.
 * `failingSince`: when the alarm first found the level due and could not fire it (absent while it fires), so the
 * stall fallback is measured from the first refusal, however late the alarm came.
 */
export type EscalationTimerRow = { id: string; at: number; failingSince?: number | null };

/** What a timeline entry records, by `kind` (RFC 0003 "TimelineEntry"). */
export type TimelineEntry =
  | { kind: "declared"; title: string; severity: Severity }
  | { kind: "status_changed"; from: IncidentStatus; to: IncidentStatus }
  | { kind: "severity_changed"; from: Severity; to: Severity }
  | { kind: "acknowledged" }
  /** `from` and `to` are member ids; null: nobody (assigned from nobody, or unassigned). */
  | { kind: "role_assigned"; role: IncidentRole; from: string | null; to: string | null }
  /** A written update (`incident.postUpdate`). */
  | { kind: "update"; body: string }
  /** The alert of the monitor that opened the incident resolved; the monitor's name as it was then. */
  | {
      kind: "alert_resolved";
      monitorId: string;
      monitor: string;
      reason: "recovered" | "paused" | "deleted";
    }
  /**
   * A page reached nobody, or not `userId` on any of their devices (`notification.fail`, RFC 0005); `schedule` names
   * an escalation level's schedule that had nobody on call (absent on other entries).
   */
  | {
      kind: "page_failed";
      userId: string | null;
      reason: PageFailure;
      schedule?: string | null;
      /**
       * The escalation page it belongs to: the run (its `eventId`) and the page's step (1-based count of the run's
       * pages), so a page's failures are told apart from the next one's. Absent outside a run.
       */
      run?: string;
      step?: number;
    }
  /**
   * An escalation level was paged (RFC 0006 "Who is paged"): `level` 1-based, or null for everyone who can respond;
   * `reason` says why this level (`EscalationReason`).
   */
  | {
      kind: "escalated";
      level: number | null;
      round: number;
      userIds: string[];
      reason: EscalationReason;
      /** Everyone who can respond after earlier levels paged someone: no later level could reach anyone. */
      later?: boolean;
      /** The run's first page: who caused it, reached without a push (they know). */
      causedBy?: string;
      /** The page before paged again, the same level and people: its event was lost. */
      again?: boolean;
    }
  /** Every level and repeat was paged and nobody acknowledged, so everyone who can respond was paged. */
  | { kind: "escalation_exhausted"; levels: number; rounds: number }
  /**
   * The email notifier could not email `userId` (`notification.failEmail`, RFC 0005 "Email"): `about` says which
   * email, the one telling a member their page did not reach them or the one telling an owner nobody was paged.
   */
  | { kind: "email_failed"; userId: string; reason: EmailFailure; about: EmailAbout }
  /** The Slack notifier gave up on the incident's channel message (`notification.failSlack`, RFC 0011). */
  | { kind: "slack_failed"; reason: SlackFailure }
  /** An update published to the status page (`incident.publishUpdate`, RFC 0012): what the public was told. */
  | { kind: "status_published"; status: PublicStatus; body: string };

/**
 * One entry of an incident's timeline: append-only, written by the mutation that made the change, in its
 * transaction (RFC 0003). The id is `<incident id>:<seq>`, so client and server number an entry alike.
 */
export type TimelineRow = {
  id: string;
  incidentId: string;
  /** 1, 2, 3… per incident, in the order the shard ran the changes. */
  seq: number;
  at: number;
  /** Who made the change: a member id or a system actor (`sys_monitors`). */
  actor: string;
} & TimelineEntry;

/**
 * A member of the workspace as the shard knows it (RFC 0003): a copy of Better Auth's D1 rows, kept for roles to
 * point at and for names to show. Written by `member.sync` when the member opens a socket.
 */
export type MemberRow = {
  id: string; // the user id (usr_<ULID>)
  /** Null when their name in D1 is not one the shard can keep (`fitMemberName`): shown as unnamed. */
  name: string | null;
  role: Role;
  updatedAt: number;
};

/** The workspace a shard serves: one row, written by `workspace.create` (RFC 0003). */
export type WorkspaceRow = {
  id: string; // ws_<ULID>, the Better Auth organization id
  name: string;
  createdAt: number;
  createdBy: string;
  /** Who is emailed when paging fails (`workspace.setEmail`); absent: `DEFAULT_EMAIL_SETTINGS`. */
  email?: EmailSettings;
};

/**
 * Who the email notifier writes to when paging fails (RFC 0005 "Email"):
 * - `unpaged`: a member a SEV1 or SEV2 page did not reach (no device, or every push failed), once per incident;
 * - `nobodyPaged`: the workspace's owners, when a page reached nobody and nothing else will page on its own.
 */
export type EmailSettings = { unpaged: boolean; nobodyPaged: boolean };

/** The last result one source reported for a monitor: a probe region, or the heartbeat endpoint. */
export type MonitorCheck = {
  source: CheckSource;
  /** When the source last checked (or the heartbeat last arrived, or its deadline passed). */
  at: number;
  /** The source's verdict after `CONSECUTIVE_CHECKS` alike results (RFC 0007), not this one check alone. */
  up: boolean;
  latencyMs: number | null;
  /** The colo the probe really ran from (RFC 0007 "Placement"): never the hint. Null for heartbeats. */
  colo: string | null;
  /** The HTTP status of the last check, if it got one. */
  httpStatus: number | null;
  /** Why the last check failed (`timeout`, `status`, `keyword`, `network`, `blocked`, `missed`); null if it passed. */
  error: string | null;
};

/**
 * A monitor (RFC 0003, 0007). Each kind's fields are null for the others: `url`, `method`, `expectedStatus` and
 * `keyword` for HTTP, `host` and `port` for TCP, `graceSeconds` for a heartbeat. `status`,
 * `checks`, `alertId` and `incidentId` are written by the server only, from probe reports and heartbeats.
 */
export type MonitorRow = {
  id: string; // mon_<ULID>, generated by the client that created it
  name: string;
  kind: MonitorKind;
  url: string | null;
  method: HttpMethod | null;
  /** The status that counts as up; null: any 2xx or 3xx (redirects are never followed). */
  expectedStatus: number | null;
  /** Text the body must contain; null: none. */
  keyword: string | null;
  /** TCP: the host name or address (IPv6 without brackets) and port connected to. */
  host: string | null;
  port: number | null;
  timeoutSeconds: number | null;
  /** Probe regions, empty for a heartbeat. */
  regions: ProbeRegion[];
  /** HTTP and TCP: how often each region checks. Heartbeat: how often a ping is expected. */
  intervalSeconds: number;
  graceSeconds: number | null;
  paused: boolean;
  /** Who paused it and when; null while it runs. */
  pausedBy: string | null;
  pausedAt: number | null;
  status: MonitorStatus;
  /** Since when `status` holds (or since the monitor was created or resumed, while pending). */
  since: number;
  /**
   * When the monitor last started over (created, its target changed, resumed): results from before are refused.
   * Unlike `since`, a status change does not move it.
   */
  restartedAt: number;
  /** One entry per source that reported, in report order. */
  checks: MonitorCheck[];
  /** The firing alert, at most one per monitor (deduplication), and the incident it opened. */
  alertId: string | null;
  incidentId: string | null;
  createdAt: number;
  createdBy: string;
  updatedAt: number;
};

/** An alert a monitor raised (RFC 0003 "Alert → incident flow"); `fingerprint` is `monitor:<id>`. */
export type AlertRow = {
  id: string; // alt_<ULID>, generated by the shard
  fingerprint: string;
  monitorId: string;
  status: AlertStatus;
  firedAt: number;
  resolvedAt: number | null;
  incidentId: string | null;
};

/**
 * A heartbeat monitor's secret side, never synced: the SHA-256 of its token (hex) and the last ping, kept exactly
 * (the synced row is refreshed at most every `REPORT_EVERY_MS`).
 */
export type HeartbeatRow = { id: string; tokenHash: string; lastPingAt: number | null };

/**
 * A member's device that pages reach (RFC 0006): server-only, so no other member ever sees its tokens or key.
 * Written by `device.register`, removed by `device.unregister` and `device.expire`.
 */
export type DeviceRow = {
  id: string; // dev_<ULID>, made by the app
  /** The member who registered it; only they can change or remove it. */
  userId: string;
  platform: DevicePlatform;
  environment: PushEnvironment;
  /** APNs device token (hex) or FCM registration token. */
  pushToken: string;
  /** PushKit token for calls (RFC 0010); null without one. */
  voipToken: string | null;
  /** HPKE public key, uncompressed P-256, base64url (`packages/push`). */
  publicKey: string;
  registeredAt: number;
  updatedAt: number;
};

/**
 * A member's device as every member of the workspace sees it (RFC 0006 "Delivery receipts"): written with `devices`
 * by `device.register` (no token, no key) and dropped with it. `lastSeenAt`: when the device last registered or
 * sent a delivery receipt, the latest sign that it was online.
 */
export type DeviceSummaryRow = {
  id: string; // the device's id (dev_<ULID>)
  userId: string;
  platform: DevicePlatform;
  environment: PushEnvironment;
  /** Whether it registered a PushKit token for calls. */
  voip: boolean;
  registeredAt: number;
  lastSeenAt: number;
};

/**
 * What one page did on one device (RFC 0006 "Delivery receipts"): planned when the shard picked the device, sent
 * when the notifier handed it to the relay, accepted when the relay said APNs took it, delivered when the phone's
 * extension reported it opened it. Each stage is a time or null; `error` is the last failed attempt's, cleared once
 * accepted. Written by `delivery.plan`, `delivery.report` and `delivery.confirm`.
 */
export type DeliveryRow = {
  id: string; // `<incident id>:<event id>:<device id>` (`deliveryId`)
  incidentId: string;
  /** The event that asked for the page. */
  eventId: string;
  deviceId: string;
  userId: string;
  platform: DevicePlatform;
  environment: PushEnvironment;
  /** The escalation page it belongs to (its run and step); null outside a run. */
  run: string | null;
  step: number | null;
  plannedAt: number;
  /** When the last attempt was handed to the relay. */
  sentAt: number | null;
  acceptedAt: number | null;
  deliveredAt: number | null;
  attempts: number;
  error: DeliveryError | null;
  /** APNs' own reason with `error` (`BadDeviceToken`), when it gave one. */
  reason: string | null;
  updatedAt: number;
};

/**
 * One layer (rotation) of a schedule (RFC 0003 "Schedules"): its members take shifts in the order listed, each
 * `count` `unit`s long on the schedule's wall clock, the first starting at `startDate` `handoffTime` there.
 */
export type ScheduleLayer = {
  id: string; // lyr_<ULID>, made by the client
  /** Empty when nobody named it: readers show "Primary", "Layer 2" in their own language. */
  name: string;
  /** Member ids in rotation order. Empty only after the last of them left (a gap until someone edits it). */
  members: string[];
  /** `YYYY-MM-DD` in the schedule's time zone; a weekly rotation hands off on this date's weekday. */
  startDate: string;
  /** `HH:MM` on the schedule's wall clock. */
  handoffTime: string;
  unit: RotationUnit;
  count: number;
};

/** An on-call schedule: its layers, stacked (a later layer wins where it has someone), in its own time zone. */
export type ScheduleRow = {
  id: string; // sch_<ULID>, made by the client
  name: string;
  /** IANA time zone every handoff is read in. */
  timeZone: string;
  layers: ScheduleLayer[];
  createdAt: number;
  createdBy: string;
  updatedAt: number;
};

/** Someone covers a schedule over `[start, end)`, over every layer (RFC 0003 "Schedules"). */
export type OverrideRow = {
  id: string; // ovr_<ULID>, made by the client; of overlapping overrides the latest `createdAt` wins, the id breaks a tie
  scheduleId: string;
  userId: string;
  start: number;
  end: number;
  createdAt: number;
  createdBy: string;
};

/**
 * The workspace's Slack connection as every member sees it (RFC 0011): one row (`SLACK_ROW_ID`), written by
 * `slack.connect`, `slack.configure` and `slack.disconnect`. Never the token.
 */
export type SlackRow = {
  id: string;
  /** The Slack team (`T…`) and its name when it was connected. */
  teamId: string;
  teamName: string;
  /** Where incidents are posted (`C…` or `G…`); null: nowhere yet. */
  channelId: string | null;
  /** The language channel messages are written in. */
  locale: SlackLocale;
  connectedAt: number;
  connectedBy: string;
  updatedAt: number;
};

/** The Slack bot token, sealed by the API (`v1.<iv>.<ciphertext>`); server-only, never synced or in an event. */
export type SlackTokenRow = {
  id: string;
  teamId: string;
  botUserId: string;
  token: string;
  scopes: string[];
};

/**
 * The workspace's public status page (RFC 0012): one row (`STATUS_PAGE_ID`), written by `statusPage.configure`
 * once the API claimed the slug in D1.
 */
export type StatusPageRow = {
  id: string;
  /** The page's address, `/status/<slug>`; unique across the instance. */
  slug: string;
  /** The name the page shows, usually the company's or the product's. */
  title: string;
  /** The language the page is written in, for every visitor. */
  locale: StatusLocale;
  /** Whether the public can read it; a page that is not enabled is a draft nobody outside sees. */
  enabled: boolean;
  updatedAt: number;
  updatedBy: string;
};

/** A part of the service the status page lists (RFC 0012 "Components"). */
export type StatusComponentRow = {
  id: string; // cmp_<ULID>, made by the client
  name: string;
  /** Components with the same group are listed together under it; null: ungrouped, listed first. */
  group: string | null;
  /** Its status set by hand; what the page shows is the worse of this and its open incidents' impact. */
  status: ComponentStatus;
  createdAt: number;
  updatedAt: number;
};

/** One update the public was given about an incident; its id is the incident's `status_published` entry. */
export type StatusUpdate = { id: string; at: number; status: PublicStatus; body: string };

/**
 * What the status page says about an incident (RFC 0012 "Publishing"): written only by `incident.publishUpdate`,
 * never from the incident's own fields, so nothing internal reaches the public unless someone wrote it for them.
 */
export type StatusIncidentRow = {
  id: string; // the incident's id
  title: string;
  status: PublicStatus;
  impact: ComponentStatus;
  componentIds: string[];
  /** Oldest first. */
  updates: StatusUpdate[];
  publishedAt: number;
  /** When it was first published as resolved; null while open (publishing again reopens it). */
  resolvedAt: number | null;
  updatedAt: number;
};

/**
 * Server-only: a slug the page gave up (`id`), whose snapshot the shard still has to delete before D1 lets anyone
 * else claim it (RFC 0012 "Addresses").
 */
export type StatusRetiredRow = { id: string; at: number };

/** Per-shard sequences, e.g. `{ id: "incident", value: 142 }`. Server-only. */
